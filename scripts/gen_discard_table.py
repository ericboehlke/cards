"""Generate internal/cribbage/discard_table.go from cards/cribbage/discard_table.py.

Run from the repo root: uv run python scripts/gen_discard_table.py
Floats are emitted with repr(), which round-trips exactly.
"""

import hashlib
import shutil
import struct
import subprocess
from pathlib import Path

from cards.cribbage.discard_table import opponent_crib_discard_table, player_crib_discard_table

OUT = Path(__file__).resolve().parent.parent / "internal" / "cribbage" / "discard_table.go"


def emit(name: str, table: dict) -> str:
    lines = [f"var {name} = map[discardKey]float64{{"]
    for a in sorted(table):
        for b in sorted(table[a]):
            lines.append(f"\t{{{a}, {b}}}: {table[a][b]!r},")
    lines.append("}")
    return "\n".join(lines)


def checksum() -> str:
    """SHA-256 over every table entry as "table a b float64-bits-hex" lines (see the Go test)."""
    h = hashlib.sha256()
    for name, table in (
        ("player", player_crib_discard_table),
        ("opponent", opponent_crib_discard_table),
    ):
        for a in sorted(table):
            for b in sorted(table[a]):
                bits = struct.unpack(">Q", struct.pack(">d", table[a][b]))[0]
                h.update(f"{name} {a} {b} {bits:016x}\n".encode())
    return h.hexdigest()


def gofmt(src: str) -> str:
    exe = shutil.which("gofmt") or str(Path.home() / "sdk" / "go" / "bin" / "gofmt")
    return subprocess.run([exe], input=src, capture_output=True, text=True, check=True).stdout


def main() -> None:
    src = f"""// Code generated by scripts/gen_discard_table.py; DO NOT EDIT.

package cribbage

// discardKey is a pair of discarded ranks (1 = ace .. 13 = king), in the order
// the Python table is indexed (first discard, second discard).
type discardKey struct{{ A, B int }}

// Schell crib discard tables
// (http://www.cribbageforum.com/SchellDiscard.htm), copied verbatim from
// cards/cribbage/discard_table.py.

{emit("playerCribDiscardTable", player_crib_discard_table)}

{emit("opponentCribDiscardTable", opponent_crib_discard_table)}

// discardTableChecksum is the SHA-256 of the Python tables, computed by the generator; the Go
// test recomputes it from the maps above.
const discardTableChecksum = "{checksum()}"

// CribDiscardValue returns the crib value of discarding cards of ranks r1 and
// r2 (1-13): the player table value if the discarder is the dealer, otherwise
// the negated opponent table value. It matches the Python
// score_discard exactly (negation is exact in float64). It panics on a
// rank outside 1-13.
func CribDiscardValue(dealer bool, r1, r2 int) float64 {{
	k := discardKey{{r1, r2}}
	if dealer {{
		v, ok := playerCribDiscardTable[k]
		if !ok {{
			panic("cribbage: discard rank out of range")
		}}
		return v
	}}
	v, ok := opponentCribDiscardTable[k]
	if !ok {{
		panic("cribbage: discard rank out of range")
	}}
	return -v
}}
"""
    OUT.write_text(gofmt(src))


if __name__ == "__main__":
    main()
